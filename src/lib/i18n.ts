export const DICTIONARIES: Record<Locale, Dict> = { en, es, pt, fr, de, ja }

/** Best supported locale for a BCP-47 tag ('pt-BR' → 'pt'); en otherwise. */
export function matchLocale(tag: string | undefined | null): Locale {
  if (!tag) return 'en'
  const base = tag.toLowerCase().split('-')[0]
  return (LOCALES as readonly string[]).includes(base) ? (base as Locale) : 'en'
}

/** Resolve the active locale from the language pref ('auto' = browser). */
export function resolveLocale(pref: string): Locale {
  if (pref !== 'auto' && (LOCALES as readonly string[]).includes(pref)) return pref as Locale
  return matchLocale(typeof navigator !== 'undefined' ? navigator.language : 'en')
}

export function t(key: string, locale: Locale): string {
  return DICTIONARIES[locale][key] ?? DICTIONARIES.en[key] ?? key
}
